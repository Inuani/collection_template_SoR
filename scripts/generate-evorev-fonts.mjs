import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repository = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetDirectory = join(repository, "assets", "evorev");
const outputPath = join(repository, "src", "ui", "evorev_fonts.mo");

const fonts = [
  ["Providence Sans", "ProvidenceSans-Regular.woff2", "400"],
  ["Providence Sans", "ProvidenceSans-Bold.woff2", "700 950"],
  ["Sketchbook Notes", "SketchbookNotes-Bold.woff2", "700"],
];

const css = fonts.map(([family, filename, weight]) => {
  const payload = readFileSync(join(assetDirectory, filename)).toString("base64");
  return `@font-face{font-family:'${family}';src:url(data:font/woff2;base64,${payload}) format('woff2');font-style:normal;font-weight:${weight};font-display:swap}`;
}).join("");

const generated = `// Generated by scripts/generate-evorev-fonts.mjs. Do not edit.\nmodule {\n  public let css : Text = ${JSON.stringify(css)};\n};\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== generated) {
    throw new Error("src/ui/evorev_fonts.mo is stale; regenerate it before building.");
  }
} else {
  writeFileSync(outputPath, generated);
}
